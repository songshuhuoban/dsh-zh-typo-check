/** @returns {{start:number,end:number,fix:string}|null} */
function offsetOf(text, wrong) {
  if (wrong === null) return null
  const at = text.indexOf(wrong)
  if (at < 0) throw new Error(`语料里找不到「${wrong}」：${text}`)
  return { start: at, end: at + wrong.length, fix: null }
}

function build(items, kind, splitFor) {
  return items.map(([text, wrong, right], index) => {
    // 一句里可能不止一个错：wrong 传 [[错, 对], ...]
    const pairs = Array.isArray(wrong) ? wrong : (wrong === null ? [] : [[wrong, right]])
    return {
      text,
      kind,
      split: splitFor(index),
      gold: pairs.map(([w, fix]) => {
        const at = text.indexOf(w)
        if (at < 0) throw new Error(`语料里找不到「${w}」：${text}`)
        return { start: at, end: at + w.length, fix }
      }),
    }
  })
}

const bySplit = (index) => (index % 2 === 0 ? 'dev' : 'test')

export const CORPUS = [
  ...build(HOMOPHONE, 'homophone', bySplit),
  ...build(IDIOM, 'idiom', bySplit),
  ...build(PUNCT, 'punct', bySplit),
  ...CLEAN.map((text, index) => ({ text, kind: 'clean', split: bySplit(index), gold: [] })),
]

